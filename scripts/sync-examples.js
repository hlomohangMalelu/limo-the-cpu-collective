

const fs = require("node:fs");
const path = require("node:path");

const dir = path.join(__dirname, "..", "examples");
const examples = {};

for (
    const file of fs
        .readdirSync(dir)
        .filter((file) => file.endsWith(".limo"))
        .sort()
) {
    const name = file.replace(/\.limo$/, "");

    // A JavaScript template literal turns CRLF into LF, so do the same here.
    const content = fs
        .readFileSync(path.join(dir, file), "utf8")
        .replace(/\r\n/g, "\n");

    examples[name] = content;
}

/** Write text as a readable multi-line template literal. */
function toTemplateLiteral(text) {
    const escaped = text
        .replace(/\\/g, "\\\\")
        .replace(/`/g, "\\`")
        .replace(/\$\{/g, "\\${");

    return `\`${escaped}\``;
}

/** Use a bare key when it is a valid identifier, otherwise quote it. */
function toKey(name) {
    return /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
}

const entries = Object.entries(examples)
    .map(([name, text]) => `        ${toKey(name)}: ${toTemplateLiteral(text)},`)
    .join("\n\n");

const out = `/*
 * GENERATED by scripts/sync-examples.js from examples/*.limo.
 * Do not edit by hand.
 */

(function (root, factory) {
    const api = factory();

    if (typeof module === "object" && module.exports) {
        module.exports = api;
    } else {
        root.LIMO = Object.assign(root.LIMO || {}, api);
    }
})(typeof self !== "undefined" ? self : this, function () {
    const EXAMPLES = {
${entries}
    };

    return { EXAMPLES };
});
`;

fs.writeFileSync(path.join(__dirname, "..", "src", "examples.js"), out);

console.log(
    "src/examples.js written:",
    Object.keys(examples).join(", ")
);
